# Main Form
col1, col2 = st.columns(2)

with col1:
    st.subheader("📍 Location & Type")
    city = st.selectbox("Select City", ["Mumbai", "Pune", "Bangalore", "New Delhi", "Nagpur", "Chennai", "Hyderabad"])
    furnishing = st.selectbox("Furnishing Status", ["Unfurnished", "Semi-Furnished", "Furnished"])
    area = st.number_input("Area (in Sq. Ft.)", min_value=100.0, max_value=20000.0, value=800.0, step=50.0)
    area_rate = st.number_input("Area Rate (₹/Sq.Ft)", min_value=1.0, max_value=50000.0, value=50.0, step=10.0, help="Average rent per square foot in this locality")

with col2:
    st.subheader("🛏️ Property Details")
    beds = st.number_input("Number of Bedrooms", min_value=1, max_value=10, value=2, step=1)
    bathrooms = st.number_input("Number of Bathrooms", min_value=1, max_value=10, value=2, step=1)
    balconies = st.number_input("Number of Balconies", min_value=0, max_value=10, value=1, step=1)

st.markdown("---")

# Prediction logic
if st.button("Predict Estimated Rent 🚀"):
    if model is None:
        st.error("Model not found! Please ensure 'model.pkl' is generated by running the training script.")
    else:
        # Prepare input data for the pipeline
        input_data = pd.DataFrame({
            'city': [city],
            'area': [area],
            'beds': [beds],
            'bathrooms': [bathrooms],
            'balconies': [balconies],
            'furnishing': [furnishing],
            'area_rate': [area_rate]
        })
        
        with st.spinner("Analyzing property details..."):
            try:
                prediction = model.predict(input_data)[0]
                st.markdown(f"""
                <div class="pred-box">
                    <p style="font-size: 1.2em; color: #B0BEC5; margin-bottom: 5px;">Estimated Monthly Rent</p>
                    <p class="pred-value">₹ {prediction:,.2f}</p>
                </div>
                """, unsafe_allow_html=True)
            except Exception as e:
                st.error(f"An error occurred during prediction: {str(e)}")

